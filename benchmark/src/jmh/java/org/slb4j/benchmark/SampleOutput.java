package org.slb4j.benchmark;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import java.util.logging.Level;
import java.util.logging.LogRecord;

public final class SampleOutput {

    private static final String ARGUMENT_MESSAGE = "Sample log output generated by {} frontend/{} backend";

    private final PrintStream originalOut = System.out;
    private final PrintStream originalErr = System.err;
    private final SwitchableOutputStream stdout = new SwitchableOutputStream(originalOut);
    private final SwitchableOutputStream stderr = new SwitchableOutputStream(originalErr);

    private SampleOutput() {
    }

    public static void main(String[] args) throws IOException, ReflectiveOperationException {
        if (args.length != 4) {
            throw new IllegalArgumentException("Expected: benchmark class, output directory, formats, frontends");
        }
        var benchmark = Class.forName(SampleOutput.class.getPackageName() + "." + args[0])
                .asSubclass(AbstractLoggingBenchmark.class).getDeclaredConstructor().newInstance();
        new SampleOutput().generate(benchmark, Path.of(args[1]), args[2].split(","), args[3].split(","));
    }

    private void generate(AbstractLoggingBenchmark benchmark, Path directory, String[] formats, String[] frontends)
            throws IOException {
        Path tempFile = Files.createTempFile(directory, benchmark.backend() + "-bench", ".log");
        try (var out = new PrintStream(stdout, false, StandardCharsets.UTF_8);
             var err = new PrintStream(stderr, false, StandardCharsets.UTF_8)) {
            System.setOut(out);
            System.setErr(err);
            for (String format : formats) {
                BenchmarkConfigurator configurator = benchmark.createConfigurator("CONSOLE", format, tempFile);
                try {
                    configurator.setup();
                    benchmark.initializeLoggers(format);
                    try {
                        for (String frontend : frontends) {
                            capture(benchmark, directory, format, frontend, false, false);
                            capture(benchmark, directory, format, frontend, false, true);
                            capture(benchmark, directory, format, frontend, true, false);
                            capture(benchmark, directory, format, frontend, true, true);
                        }
                    } finally {
                        AbstractLoggingBenchmark.clearLoggingContext();
                    }
                } finally {
                    configurator.tearDown();
                }
            }
        } finally {
            System.setOut(originalOut);
            System.setErr(originalErr);
            Files.deleteIfExists(tempFile);
        }
    }

    private void capture(AbstractLoggingBenchmark benchmark, Path directory, String format, String frontend,
                         boolean arguments, boolean withException) throws IOException {
        String filename = "%s-%s-%s%s.out".formatted(format, frontend, arguments ? "ARGUMENTS" : "CONSTANT",
                withException ? "-EXCEPTION" : "");
        var output = new ByteArrayOutputStream();
        stdout.setTarget(output);
        stderr.setTarget(output);
        try {
            Throwable exception = withException ? new IllegalStateException("Sample exception") : null;
            if (arguments) {
                logArguments(benchmark, frontend, exception);
            } else {
                logConstant(benchmark, frontend, exception);
            }
            System.out.flush();
            System.err.flush();
        } finally {
            stdout.setTarget(originalOut);
            stderr.setTarget(originalErr);
        }
        Files.write(directory.resolve(filename), output.toByteArray());
    }

    private static void logConstant(AbstractLoggingBenchmark benchmark, String frontend, Throwable exception) {
        String message = "Sample log output generated by " + frontend.toUpperCase(Locale.ROOT)
                + " frontend/" + benchmark.backend() + " backend";
        switch (frontend) {
            case "jul" -> benchmark.julLogger.log(Level.INFO, message, exception);
            case "jcl" -> benchmark.jclLogger.info(message, exception);
            case "log4j" -> benchmark.log4jLogger.info(message, exception);
            case "slf4j" -> benchmark.slf4jLogger.info(message, exception);
            default -> throw new IllegalArgumentException("Unknown frontend: " + frontend);
        }
    }

    private static void logArguments(AbstractLoggingBenchmark benchmark, String frontend, Throwable exception) {
        String label = frontend.toUpperCase(Locale.ROOT);
        String backend = benchmark.backend();
        switch (frontend) {
            case "jul" -> {
                var record = new LogRecord(Level.INFO, "Sample log output generated by {0} frontend/{1} backend");
                record.setLoggerName(benchmark.julLogger.getName());
                record.setParameters(new Object[]{label, backend});
                record.setThrown(exception);
                benchmark.julLogger.log(record);
            }
            case "log4j" -> benchmark.log4jLogger.info(ARGUMENT_MESSAGE, label, backend, exception);
            case "slf4j" -> benchmark.slf4jLogger.info(ARGUMENT_MESSAGE, label, backend, exception);
            case "jcl" -> { /* No parameterized overload. */ }
            default -> throw new IllegalArgumentException("Unknown frontend: " + frontend);
        }
    }
}