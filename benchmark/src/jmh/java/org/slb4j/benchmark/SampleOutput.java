package org.slb4j.benchmark;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.ByteBuffer;
import java.nio.channels.FileChannel;
import java.nio.channels.FileLock;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.function.BiConsumer;
import java.util.function.Consumer;

final class SampleOutput {

    static final String REPORT_ENV = "SLB4J_SAMPLE_OUTPUT_FILE";
    private static final Object REPORT_LOCK = new Object();

    private SampleOutput() {
    }

    static void installJulToSlf4jBridge() {
        try {
            Class<?> bridge = Class.forName("org.slf4j.bridge.SLF4JBridgeHandler");
            bridge.getMethod("removeHandlersForRootLogger").invoke(null);
            bridge.getMethod("install").invoke(null);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Could not install the JUL-to-SLF4J bridge", e);
        }
    }

    static void writeIfConfigured(
            String backend,
            String category,
            String format,
            Path outputFile,
            SwitchableOutputStream stdout,
            SwitchableOutputStream stderr,
            PrintStream originalOut,
            PrintStream originalErr,
            org.slf4j.Logger slf4jLogger,
            org.apache.commons.logging.Log jclLogger,
            org.apache.logging.log4j.Logger log4jLogger,
            java.util.logging.Logger julLogger
    ) throws IOException {
        String reportName = System.getenv(REPORT_ENV);
        if (reportName == null || reportName.isBlank()) {
            return;
        }

        String normalizedBackend = backend.toUpperCase(Locale.ROOT);
        List<Frontend> frontends = List.of(
                new Frontend("JUL", message -> julLogger.info(message),
                        (message, exception) -> julLogger.log(java.util.logging.Level.INFO, message, exception)),
                new Frontend("JCL", message -> jclLogger.info(message), jclLogger::info),
                new Frontend("LOG4J", message -> log4jLogger.info(message), log4jLogger::info),
                new Frontend("SLF4J", message -> slf4jLogger.info(message), slf4jLogger::info)
        );

        List<Sample> samples = new ArrayList<>();
        for (Frontend frontend : frontends) {
            String message = "Sample log output generated by " + frontend.name + " frontend";
            String plain = capture(category, outputFile, stdout, stderr, originalOut, originalErr,
                    () -> frontend.plainLog.accept(message));
            String exception = capture(category, outputFile, stdout, stderr, originalOut, originalErr,
                    () -> frontend.exceptionLog.accept(message, new IllegalStateException("Sample exception")));
            validateCaptured(frontend.name, normalizedBackend, false, message, plain);
            validateCaptured(frontend.name, normalizedBackend, true, message, exception);
            samples.add(new Sample(frontend.name, false, plain));
            samples.add(new Sample(frontend.name, true, exception));
        }

        appendSamples(Path.of(reportName).toAbsolutePath(), format, normalizedBackend, samples);
    }

    static void validateCaptured(String frontend, String backend, boolean exception, String message, String output) throws IOException {
        if (!output.contains(message)) {
            throw new IOException("Incomplete output captured for " + frontend + "/" + backend
                    + "\n  expected message: '" + message.replaceAll("\n", "\\\\n") + "'"
                    + "\n  actual output:    '" + output.replaceAll("\n", "\\\\n") + "'"
            );
        }
        if (exception && !output.contains("Sample exception")) {
            throw new IOException("Invalid exception captured for " + frontend + "/" + backend
                    + "\n  expected exception: 'Sample exception'"
                    + "\n  actual exception:   '" + output.replaceAll("\n", "\\\\n") + "'"
            );
        }
    }

    private static String capture(
            String category,
            Path outputFile,
            SwitchableOutputStream stdout,
            SwitchableOutputStream stderr,
            PrintStream originalOut,
            PrintStream originalErr,
            Runnable log
    ) throws IOException {
        long start = "FILE".equals(category) && outputFile != null && Files.exists(outputFile)
                ? Files.size(outputFile)
                : 0;
        ByteArrayOutputStream captured = new ByteArrayOutputStream();
        if ("CONSOLE".equals(category)) {
            stdout.setTarget(captured);
            stderr.setTarget(captured);
        }

        try {
            log.run();
            System.out.flush();
            System.err.flush();
        } finally {
            if ("CONSOLE".equals(category)) {
                stdout.setTarget(originalOut);
                stderr.setTarget(originalErr);
            }
        }

        if ("FILE".equals(category)) {
            if (outputFile == null || !Files.exists(outputFile)) {
                throw new IOException("No backend output file was available for sample capture");
            }
            byte[] output = Files.readAllBytes(outputFile);
            int offset = (int) Math.min(start, output.length);
            return new String(output, offset, output.length - offset, StandardCharsets.UTF_8);
        }

        return captured.toString(StandardCharsets.UTF_8);
    }

    static void appendSamples(Path report, String format, String backend, List<Sample> samples) throws IOException {
        Files.createDirectories(report.getParent());
        synchronized (REPORT_LOCK) {
            try (FileChannel channel = FileChannel.open(report, StandardOpenOption.CREATE, StandardOpenOption.READ, StandardOpenOption.WRITE);
                 FileLock ignored = channel.lock()) {
                if (channel.size() > Integer.MAX_VALUE) {
                    throw new IOException("Sample output report is unexpectedly large");
                }
                ByteBuffer existingBytes = ByteBuffer.allocate((int) channel.size());
                channel.position(0);
                while (existingBytes.hasRemaining() && channel.read(existingBytes) >= 0) {
                    // Read the current report while holding the cross-process lock.
                }
                existingBytes.flip();
                String updated = StandardCharsets.UTF_8.decode(existingBytes).toString();
                for (Sample sample : samples) {
                    if (sample.output.isBlank()) {
                        throw new IOException("No output captured for " + sample.frontend + "/" + backend);
                    }
                    String kind = sample.exception ? "exception" : "plain";
                    String key = "<!-- sample-output:" + format + ":" + sample.frontend + ":" + kind + ":" + backend + " -->";
                    if (updated.contains(key)) {
                        continue;
                    }
                    String suffix = sample.exception ? " (with exception)" : "";
                    String heading = "## Format: " + format + ", Frontend " + sample.frontend + suffix + "\n\n````text\n";
                    int start = updated.indexOf(heading);
                    int end = start < 0 ? -1 : updated.indexOf("````\n", start + heading.length());
                    if (end < 0) {
                        throw new IOException("Missing sample output section: " + heading.strip());
                    }
                    String prefix = "%-12s".formatted(backend + ":");
                    String output = sample.output.stripTrailing().replace("\r\n", "\n")
                            .replace("\n", "\n" + " ".repeat(prefix.length()));
                    updated = updated.substring(0, end) + prefix + output + "\n"
                            + updated.substring(end, end + 5) + key + "\n" + updated.substring(end + 5);
                }

                channel.truncate(0);
                channel.position(0);
                ByteBuffer updatedBytes = StandardCharsets.UTF_8.encode(updated);
                while (updatedBytes.hasRemaining()) {
                    channel.write(updatedBytes);
                }
                channel.force(true);
            }
        }
    }

    record Sample(String frontend, boolean exception, String output) {
    }

    private record Frontend(
            String name,
            Consumer<String> plainLog,
            BiConsumer<String, Throwable> exceptionLog
    ) {
    }
}
